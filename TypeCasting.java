class TypeCasting {
    public static void main(String[] args){  //Automatic Type Casting
        double num = 10.89;
        int a = (int) num;
        System.out.println(a);
        char ch = 'Z';
        int b = (int) ch;
        System.out.println(b);
        
    }
}

// TypeCasting are of two types AUTOMATIC and MANUAL